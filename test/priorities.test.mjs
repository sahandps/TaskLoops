import {createSuite} from './harness.mjs';
export default async function run(mod) {
 const {eq,results}=createSuite('Markdown priorities and project preferences');
 const raw='- [ ] Release - Due date: 2026-10-23 Deadline: 2026-10-25 ^release';
 const marked=mod.writeSchedule(raw,{due:'2026-10-23',deadline:'2026-10-25',priority:'high'},'YYYY-MM-DD');
 eq(mod.parseSchedule(marked).schedule,{due:'2026-10-23',deadline:'2026-10-25',priority:'high'},'priority round trips beside dates and block ID');
 eq(mod.taskWording(marked),'Release','metadata stays out of editable task wording');
 const moved=mod.writeSchedule(marked,{due:'2026-10-26'},'YYYY-MM-DD');
 eq(mod.parseSchedule(moved).schedule,{due:'2026-10-26',priority:'high'},'calendar rescheduling preserves priority');
 const cleared=mod.writeSchedule(marked,{},'YYYY-MM-DD');
 eq(mod.parseSchedule(cleared).schedule,{priority:'high'},'clearing dates preserves priority');
 eq(mod.writeSchedule(marked,{due:'2026-10-23',deadline:'2026-10-25',priority:''},'YYYY-MM-DD'),raw,'priority can be explicitly removed without losing dates or block ID');
 const unscheduled=mod.writeSchedule('- [ ] Read',{priority:'low'},'YYYY-MM-DD');
 eq(mod.parseSchedule(unscheduled).schedule,{priority:'low'},'undated tasks can have a priority');
 const task={raw:marked,line:0,path:'Project.md'};
 const edited=mod.editedBlock(marked,task,'Updated',{due:'2026-10-23',deadline:'2026-10-25'},'YYYY-MM-DD',[]);
 eq(mod.parseSchedule(edited[0]).schedule.priority,'high','title edits retain priority when omitted by caller');
 const priorityOnly=mod.editedBlock(marked,task,'Release',{due:'2026-10-23',deadline:'2026-10-25',priority:'low'},'YYYY-MM-DD',[]);
 eq(mod.parseSchedule(priorityOnly[0]).schedule.priority,'low','priority-only edits save');
 const deferred=mod.editedBlock(marked,task,'Release',{priority:'medium'},'YYYY-MM-DD',[],'Waiting for review');
 eq(mod.parseSchedule(deferred[0]).schedule,{priority:'medium'},'deferral keeps selected priority while clearing dates');
 const defaults=mod.normalizeSettings();
 eq(defaults.priorities.map(p=>p.name),['Low','Medium','High'],'default levels are available to upgraded installations');
 const custom=mod.normalizeSettings({priorities:[{id:'urgent',name:' Urgent ',color:'#aa1122'},{id:'urgent',name:'Duplicate',color:'#aabbcc'},{id:'bad',name:'',color:'red'}],projectColors:{'Project.md':'#123456','Bad.md':'red'}});
 eq(custom.priorities,[{id:'urgent',name:'Urgent',color:'#aa1122'}],'custom priorities validate and deduplicate stable IDs');
 eq(custom.projectColors,{'Project.md':'#123456'},'project colors validate before use');
 custom.priorities[0].name='Changed';
 eq(mod.normalizeSettings().priorities[0].name,'Low','draft edits do not mutate defaults');
 const colored=mod.writeSchedule(marked,{due:'2026-10-23',priority:'high',color:'#7654ac'},'YYYY-MM-DD');
 eq(mod.parseSchedule(colored).schedule,{due:'2026-10-23',priority:'high',color:'#7654ac'},'bar colors round trip beside priorities');
 eq(mod.taskWording(colored),'Release','color metadata stays out of task wording');
 eq(mod.parseSchedule(mod.writeSchedule(colored,{due:'2026-10-24'},'YYYY-MM-DD')).schedule.color,'#7654ac','rescheduling retains custom bar color');
 eq(mod.parseSchedule(mod.writeSchedule(colored,{color:''},'YYYY-MM-DD')).schedule.color,undefined,'reset removes custom bar color');
 const colorEdit=mod.editedBlock(marked,task,'Release',{due:'2026-10-23',deadline:'2026-10-25',color:'#112233'},'YYYY-MM-DD',[]);
 eq(mod.parseSchedule(colorEdit[0]).schedule.color,'#112233','color-only edits save');
 eq(mod.parseSchedule(colorEdit[0]).schedule.priority,'high','color-only edits preserve priority');
 eq(mod.validSchedule({color:'red'}),false,'invalid colors cannot be written to Markdown');
 return results;
}
