import { createSuite } from './harness.mjs';
export default async function run(mod) {
 const {eq,results}=createSuite('note grid, scan scope and searchable settings');
 const {noteGroups,inScanFolder,scanVault,TaskLoopsSettingTab,TaskLoopsPlugin,TestFile}=mod;
 const task=(path,text,checked=false,due=undefined)=>({path,text,checked,due,checkbox:true});
 const tasks=[task('Work/Alpha.md','Send launch plan',false,'2026-10-16'),task('Work/Alpha.md','Already sent',true),task('Personal/Zebra.md','Buy fruit'),task('Work/Closed.md','Finished',true),task('Root.md','Undated')];
 eq(noteGroups(tasks,'',null,'all','2026-10-16').map(g=>g.path),['Work/Alpha.md','Work/Closed.md','Root.md','Personal/Zebra.md'],'notes sort by name');
 eq(noteGroups(tasks,'launch',null,'all','2026-10-16')[0].tasks.length,2,'search matches a task and retains note context');
 eq(noteGroups(tasks,'ALPHA',null,'all','2026-10-16').length,1,'search matches note names case insensitively');
 eq(noteGroups(tasks,'','Work','open','2026-10-16').map(g=>g.path),['Work/Alpha.md'],'folder and open filters combine');
 eq(noteGroups(tasks,'',null,'today','2026-10-16').map(g=>g.path),['Work/Alpha.md'],'today only matches open due tasks');
 eq(noteGroups(tasks,'',null,'undated','2026-10-16').map(g=>g.path),['Root.md','Personal/Zebra.md'],'completed undated tasks do not match');
 eq(noteGroups(tasks,'','', 'all','2026-10-16').map(g=>g.path),['Root.md'],'vault root is a distinct folder');
 eq(noteGroups(tasks,'missing',null,'all','2026-10-16'),[],'empty search results');
 eq(inScanFolder('Work/Alpha.md','/Work/'),true,'scope tolerates trailing slashes');
 eq(inScanFolder('Work/Sub/Alpha.md','Work'),true,'scope includes nested folders');
 eq(inScanFolder('Workshop/Alpha.md','Work'),false,'scope respects folder boundary');
 eq(inScanFolder('Alpha.md',''),true,'blank scope includes vault root');
 const read=[];
 await scanVault({vault:{getMarkdownFiles:()=>[{path:'Work/Alpha.md'},{path:'Personal/Secret.md'}],cachedRead:async file=>{read.push(file.path);return '- [ ] Task';}},metadataCache:{getFileCache:()=>({listItems:[{task:' ',position:{start:{line:0}}}]})}},'#task','checkboxes','Work');
 eq(read,['Work/Alpha.md'],'out of scope note contents are not read');
 const plugin=new TaskLoopsPlugin();
 plugin.settings={defaultView:'notes',notePreviewLimit:5,dateFormat:'YYYY-MM-DD',standaloneNote:'Standalone Tasks.md',scanFolder:''};
 let saves=0,refresh=0;
 plugin.saveSettings=async()=>{saves++;};plugin.refreshViews=()=>{refresh++;};
 const tab=new TaskLoopsSettingTab({},plugin);
 const defs=tab.getSettingDefinitions();
 eq(defs.map(d=>d.name),['General','Default view','Planner theme','Calendar','Date format','Time display','Week starts on','Calendar scale','Timeline opening hour','Show week numbers','Calendar zoom','Tasks','Default task duration','Show completed by default','Standalone task storage','Standalone tasks note','Task scan folder','Show progress bars','Task priorities','Daily note calendar','Daily calendar week starts on','Daily calendar week numbers','Daily calendar weekend shading','Daily calendar note dots','Notes','Tasks per note card','Note card spacing','Projects','Project colors'],'settings are grouped and remain searchable');
 let change;
 const dropdown={addOption:()=>dropdown,setValue:()=>dropdown,onChange:fn=>{change=fn;return dropdown;}};
 defs.find(d=>d.name==='Default view').render({addDropdown:fn=>fn(dropdown)});
 await change('planner');
 eq(plugin.settings.defaultView,'planner','default view updates');
 eq([saves,refresh],[1,1],'settings save through plugin wrapper and refresh views');
 const file=new TestFile();let opened,type;
 plugin.app={vault:{getAbstractFileByPath:()=>file},workspace:{getLeaf:t=>{type=t;return{openFile:async(...args)=>{opened=args;}};}}};
 await plugin.reveal({path:'Work/Alpha.md',line:42});
 eq(type,'tab','source navigation creates a new tab');
 eq(opened[1],{eState:{line:42},active:true},'source navigation preserves task line');
 defs.find(d=>d.name==='Standalone task storage').render({addDropdown:fn=>fn(dropdown)});
 await change('daily');
 eq(plugin.settings.standaloneDestination,'daily','settings control selects daily notes for standalone tasks');
 await change('note');
 eq(plugin.settings.standaloneDestination,'note','settings control restores the configured standalone note');
 eq([saves,refresh],[3,3],'standalone storage preference saves and refreshes');
 return results;
}
