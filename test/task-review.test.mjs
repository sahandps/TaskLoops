import { createSuite } from './harness.mjs';
export default function run(mod) {
 const {eq,results}=createSuite('overdue review and filtering');
 const task=(id,due,deadline,checked=false,path='Work.md')=>({id,text:id,path,line:0,due,deadline,checked});
 const today='2026-10-20';
 const old=task('old','2026-10-10');
 const past=task('past due','2026-10-19');
 const span=task('active span','2026-10-10','2026-10-22');
 const deadline=task('past deadline','2026-10-01','2026-10-18');
 const dueToday=task('today','2026-10-20');
 const lastDay=task('last day','2026-10-01',today);
 const undated=task('unscheduled');
 const done=task('finished','2026-10-01',undefined,true);
 const future=task('future','2026-10-21');
 const tasks=[span,deadline,old,dueToday,undated,done,future,past,lastDay];
 eq(mod.overdueDays(past,today),1,'yesterday is one day overdue');
 eq(mod.overdueDays(deadline,today),2,'deadline takes priority over original due date');
 eq(mod.overdueDays(span,today),0,'multi-day task with future deadline is still active');
 eq(mod.overdueDays(lastDay,today),0,'deadline remains valid through its final day');
 eq(mod.overdueDays(dueToday,today),0,'today is not late');
 eq(mod.overdueDays(undated,today),0,'undated task is not late');
 eq(mod.overdueDays(future,today),0,'future task is not late');
 eq(mod.overdueDays(done,today),0,'completed task is never overdue');
 eq(mod.overdueDays(task('dst','2026-10-24'),'2026-10-27'),3,'day count stays correct through DST');
 eq(mod.overdueDays(task('leap','2024-02-28'),'2024-03-01'),2,'day count includes leap day');
 const overdue=mod.reviewTasks(tasks,'',false,'overdue',today);
 eq(overdue.listed.map(t=>t.id),['old','past deadline','past due'],'overdue list shows oldest final date first');
 eq(overdue.overdueCount,3,'count includes only unfinished tasks past final day');
 eq(overdue.matching.length,8,'sidebar overdue selection preserves full calendar result');
 eq(mod.reviewTasks(tasks,'',false,'undated',today).listed.map(t=>t.id),['unscheduled'],'unscheduled is an independent mode');
 eq(mod.reviewTasks(tasks,'',true,'overdue',today).listed.map(t=>t.id),['old','past deadline','past due'],'show completed cannot contaminate overdue list');
 eq(mod.reviewTasks(tasks,'',true,'all',today).listed.length,9,'all mode respects show completed');
 const search=mod.reviewTasks(tasks,'  PAST  ',false,'overdue',today);
 eq(search.listed.map(t=>t.id),['past deadline','past due'],'search narrows overdue tasks');
 eq(search.overdueCount,2,'count matches search scope');
 eq(mod.reviewTasks(tasks,'work.md',false,'overdue',today).overdueCount,3,'source note paths are searchable');
 eq(mod.reviewTasks(tasks,'nothing',false,'overdue',today).listed,[],'empty overdue search is safe');
 eq(mod.noteGroups(tasks,'',null,'overdue',today).map(g=>g.path),['Work.md'],'Notes includes overdue notes');
 eq(mod.noteGroups([span,lastDay,done],'',null,'overdue',today),[],'Notes excludes active spans and completed tasks');
 eq(mod.reviewTasks([{...past,checked:true}],'',false,'overdue',today).overdueCount,0,'completion removes task from review');
 eq(mod.reviewTasks([{...past,due:'2026-10-21'}],'',false,'overdue',today).overdueCount,0,'rescheduling future removes task from review');
 eq(mod.noteGroups(tasks,'',null,'overdue',today)[0].tasks.slice(0,3).map(t=>t.id),['old','past deadline','past due'],'Notes shows overdue tasks before context so preview limit cannot hide them');
 return results;
}
